def fill(template: str, **kwargs: str) -> str:
    """Подстановка без str.format, чтобы фигурные скобки JSON-схем не ломали шаблон."""
    out = template
    for k, v in kwargs.items():
        out = out.replace("{" + k + "}", v)
    return out
